#!/usr/bin/env python3
"""Cross-check pycdc's opcode tables and AST-builder cases against each pinned
CPython's own opcode table, and against the opcodes our compiled corpus uses.

For every pinned interpreter version X.Y this reports, per CPython opcode:
  table    pycdc's bytes/python_X_Y.cpp maps the same raw number to the same
           name ("ok"), to a different name ("WRONG"), or not at all ("missing")
  handled  ASTree.cpp's BuildFromCode switch has a case for pycdc's internal
           name (otherwise the default branch reports "Unsupported opcode")
  used     how often the raw opcode occurs in the compiled corpus .pyc files

INSTRUMENTED_* and ENTER_EXECUTOR are runtime-only and never appear in .pyc
files written by the compiler; they are listed separately.

usage: opcode_coverage.py --pyc-root build/difftest/features --out report.md [--json out.json]
                          [--source-root TREE]   (default: this repository)
"""

import argparse
import glob
import json
import os
import re
import sys

TOOLS = os.path.dirname(os.path.realpath(__file__))
HARNESS = os.path.dirname(TOOLS)
REPO = os.path.dirname(HARNESS)
sys.path.insert(0, HARNESS)
import difftest  # noqa: E402
import sandbox  # noqa: E402

RUNTIME_ONLY = re.compile(r'^(INSTRUMENTED_|ENTER_EXECUTOR$)')


def pycdc_table(root, minor):
    path = os.path.join(root, 'bytes', 'python_%s.cpp' % minor.replace('.', '_'))
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return {int(n): name for n, name in re.findall(r'MAP_OP\((\d+),\s*(\w+)\)', f.read())}


def ast_cases(root):
    with open(os.path.join(root, 'ASTree.cpp')) as f:
        return set(re.findall(r'case Pyc::(\w+)\s*:', f.read()))


def base_name(internal):
    return internal[:-2] if internal.endswith('_A') else internal


def inventory(minor, entry, pycs, workdir, mode):
    os.makedirs(workdir, exist_ok=True)
    out = os.path.join(workdir, 'inventory-%s.json' % minor)
    argv = [entry['path'], '-s', '-B', os.path.join(HARNESS, 'workers', 'opcode_inventory.py'),
            out] + pycs
    read_allow = [REPO, os.path.dirname(os.path.dirname(os.path.realpath(entry['path'])))]
    r = sandbox.run(argv, workdir, mode, 120, read_allow=read_allow, tag='inventory-' + minor)
    if r.returncode != 0:
        sys.exit('inventory failed for %s: %s' % (minor, r.stderr.decode()[-500:]))
    with open(out) as f:
        return json.load(f)


def analyze(minor, inv, table, cases):
    rows = []
    for name, num in sorted(inv['opmap'].items(), key=lambda kv: kv[1]):
        runtime = bool(RUNTIME_ONLY.match(name))
        internal = table.get(num) if table is not None else None
        if internal is None:
            tstate = 'missing'
        elif base_name(internal) == name:
            tstate = 'ok'
        else:
            tstate = 'WRONG'
        rows.append({'name': name, 'num': num, 'runtime_only': runtime, 'table': tstate,
                     'pycdc_name': internal, 'handled': bool(internal and internal in cases),
                     'used': inv['corpus_counts'].get(name, 0)})
    extraneous = []
    if table is not None:
        cpy = {num: name for name, num in inv['opmap'].items()}
        for num, internal in sorted(table.items()):
            if num not in cpy:
                extraneous.append((num, internal))
    return rows, extraneous


def render(results):
    out = ['# Opcode coverage audit', '',
           'Generated by `harness/tools/opcode_coverage.py`. CPython tables come from each pinned '
           'interpreter\'s `dis.opmap` (values < 256); "used" counts raw opcodes in the compiled '
           'feature corpus (all optimization levels). "handled" means ASTree.cpp has a '
           '`case Pyc::<name>` label; an unhandled opcode reaches the switch default and is reported '
           'as "Unsupported opcode". Static cross-check only; whether a handled opcode is decompiled '
           'correctly is measured by the differential harness, not here.', '',
           '## Summary', '',
           '| version | CPython opcodes (on-disk) | table ok | table WRONG | table missing | '
           'handled | used in corpus | used but unhandled or unmapped | pycdc entries with no CPython opcode |',
           '| --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for minor, res in results.items():
        rows = [r for r in res['rows'] if not r['runtime_only']]
        used = [r for r in rows if r['used']]
        bad_used = [r for r in used if r['table'] != 'ok' or not r['handled']]
        out.append('| %s (%s) | %d | %d | %d | %d | %d | %d | %d | %s |' % (
            minor, res['version'], len(rows), sum(r['table'] == 'ok' for r in rows),
            sum(r['table'] == 'WRONG' for r in rows), sum(r['table'] == 'missing' for r in rows),
            sum(r['handled'] for r in rows), len(used), len(bad_used),
            'no table' if res['table_size'] is None else len(res['extraneous'])))
    for minor, res in results.items():
        rows = [r for r in res['rows'] if not r['runtime_only']]
        out += ['', '## %s' % minor, '']
        if res['table_size'] is None:
            out.append('pycdc has no `bytes/python_%s.cpp` table; every opcode is undecodable.'
                       % minor.replace('.', '_'))
        bad = [r for r in rows if r['used'] and (r['table'] != 'ok' or not r['handled'])]
        out += ['Used by the corpus but WRONG, missing or unhandled (%d):' % len(bad), '',
                '| opcode | number | table | pycdc name | handled | uses |',
                '| --- | --- | --- | --- | --- | --- |']
        for r in sorted(bad, key=lambda r: -r['used']):
            out.append('| %s | %d | %s | %s | %s | %d |' % (r['name'], r['num'], r['table'],
                                                         r['pycdc_name'] or '-',
                                                         'yes' if r['handled'] else 'no',
                                                         r['used']))
        wrong = [r for r in rows if r['table'] == 'WRONG']
        if wrong:
            out += ['', 'Table entries that disagree with CPython:', '']
            out += ['- %d: CPython `%s`, pycdc `%s`' % (r['num'], r['name'], r['pycdc_name'])
                    for r in wrong]
        if res['extraneous']:
            out += ['', 'pycdc table numbers with no CPython opcode in this version: '
                    + ', '.join('%d=%s' % e for e in res['extraneous'])]
        unused_missing = [r['name'] for r in rows if not r['used'] and
                          (r['table'] != 'ok' or not r['handled'])]
        out += ['', 'Not used by the corpus and WRONG/missing/unhandled (%d): %s' % (
            len(unused_missing), ', '.join(unused_missing) or 'none')]
        unused = [r['name'] for r in rows if not r['used']]
        out += ['', 'Never emitted by the corpus (fixture coverage gap or not emittable by the '
                'compiler) (%d): %s' % (len(unused), ', '.join(unused) or 'none')]
    out += ['', '## Caveats', '',
            '- `EXTENDED_ARG`: `bc_next` folds one prefix into the following instruction, so '
            'the switch only sees a second consecutive prefix. "Unhandled" overstates its gap.',
            '- `CACHE`: decoded as its own instruction and handled as a no-op in the switch.',
            '- Some opcodes are consumed by look-ahead inside other cases (extra `bc_next` calls); '
            'this static check cannot see that.']
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--pyc-root', required=True,
                    help='a run workroot suite dir, e.g. build/difftest/features')
    ap.add_argument('--out', required=True)
    ap.add_argument('--json')
    ap.add_argument('--workdir', default=os.path.join(REPO, 'build', 'difftest', 'opcodes'))
    ap.add_argument('--source-root', default=REPO,
                    help='decompiler source tree whose tables and ASTree.cpp are audited')
    args = ap.parse_args()
    interps = difftest.resolve_interpreters()
    mode = sandbox.default_mode()
    cases = ast_cases(args.source_root)
    results = {}
    for minor, entry in interps.items():
        if entry['status'] != 'ok':
            sys.exit('interpreter %s unavailable: %s' % (minor, entry.get('reason')))
        pycs = sorted(glob.glob(os.path.join(os.path.realpath(args.pyc_root), '*', '%s-O*' % minor,
                                            'fixture.pyc')))
        inv = inventory(minor, entry, pycs, os.path.realpath(args.workdir), mode)
        table = pycdc_table(args.source_root, minor)
        rows, extraneous = analyze(minor, inv, table, cases)
        results[minor] = {'version': inv['version'], 'corpus_files': inv['corpus_files'],
                          'table_size': None if table is None else len(table),
                          'cache_entries': inv['cache_entries'], 'rows': rows,
                          'extraneous': extraneous}
    with open(args.out, 'w') as f:
        f.write(render(results))
    if args.json:
        with open(args.json, 'w') as f:
            json.dump(results, f, indent=1, sort_keys=True)
            f.write('\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())

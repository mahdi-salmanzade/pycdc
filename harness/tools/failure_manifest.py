#!/usr/bin/env python3
"""Render a failure manifest from a difftest results file.

Groups FAIL cases by (stage, kind, cause) per suite, lists crashes and
timeouts, every silent behavior mismatch (pycdc exited 0 without diagnostics,
the output compiled, the behavior differs) with its first observed
difference, and the outputs that were explicitly marked incomplete or had
diagnostics but were executed anyway for information.

usage: failure_manifest.py RESULTS.json > FAILURES.md
"""

import collections
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.realpath(__file__))))
from difftest import STAGES, version_tuple  # noqa: E402


def cell(s, n=140):
    s = str(s).replace('|', '\\|').replace('\n', ' ')
    return s if len(s) <= n else s[:n] + '…'


def compact(cases):
    """fixture -> sorted 'ver:O0,1,2' strings."""
    by = collections.defaultdict(lambda: collections.defaultdict(set))
    for c in cases:
        by[c['fixture']][c['version']].add(c['opt'])
    out = []
    for fx in sorted(by):
        vs = ' '.join('%s(O%s)' % (v, ','.join(map(str, sorted(by[fx][v]))))
                      for v in sorted(by[fx], key=version_tuple))
        out.append('`%s` %s' % (fx, vs))
    return out


def main():
    with open(sys.argv[1]) as f:
        data = json.load(f)
    cases = data['cases']
    meta = data['meta']
    out = ['# Failure manifest', '',
           'Generated by `harness/tools/failure_manifest.py %s` from the results created %s '
           '(decompiler source `%s`, harness `%s`).' % (
               os.path.basename(sys.argv[1]), meta['created_utc'],
               meta['provenance'].get('source_head'), meta['provenance'].get('harness_head')),
           '', 'Each case is counted once, at its earliest failing stage.', '']

    for suite in sorted({c['suite'] for c in cases}):
        sc = [c for c in cases if c['suite'] == suite]
        fails = [c for c in sc if c['outcome'] == 'FAIL']
        out += ['## Suite `%s`: %d FAIL of %d cases' % (suite, len(fails), len(sc)), '']
        for st in STAGES:
            sf = [c for c in fails if c['stage'] == st]
            if not sf:
                continue
            groups = collections.defaultdict(list)
            for c in sf:
                groups[(c.get('kind'), c.get('cause'))].append(c)
            out += ['### %s (%d cases, %d distinct causes)' % (st, len(sf), len(groups)), '',
                    '| cases | kind | cause | versions |', '| --- | --- | --- | --- |']
            for (kind, cause), cs in sorted(groups.items(), key=lambda kv: -len(kv[1])):
                vs = sorted({c['version'] for c in cs}, key=version_tuple)
                out.append('| %d | %s | %s | %s |' % (len(cs), kind, cell(cause), ', '.join(vs)))
            out.append('')

        crashes = [c for c in fails if c.get('kind') in ('crash', 'timeout')]
        out += ['### Crashes and timeouts (%d)' % len(crashes), '']
        for c in sorted(crashes, key=lambda c: (c['fixture'], version_tuple(c['version']), c['opt'])):
            out.append('- `%s` %s -O%d at %s: %s' % (c['fixture'], c['version'], c['opt'],
                                                    c['stage'], c['cause']))
        out.append('')

        silent = [c for c in fails if c['stage'] == 'behavior']
        if silent:
            out += ['### Silent semantic mismatches (%d)' % len(silent), '',
                    'pycdc exited 0 with no diagnostics and no incomplete marker, and the '
                    'output compiled, but its observable behavior differs from the compiled '
                    'program. These are the most dangerous failures: nothing in the '
                    'output signals them.', '',
                    '| fixture | versions | channels | first difference (one example) |',
                    '| --- | --- | --- | --- |']
            byfx = collections.defaultdict(list)
            for c in silent:
                byfx[c['fixture']].append(c)
            for fx in sorted(byfx):
                cs = byfx[fx]
                vs = sorted({c['version'] for c in cs}, key=version_tuple)
                ex = cs[0]['stages']['behavior']
                out.append('| `%s` | %s | %s | %s |' % (
                    fx, ', '.join(vs), cell(', '.join(ex.get('channels', [])), 80),
                    cell(ex.get('first_difference', ''), 220)))
            out.append('')

        informational = [c for c in fails if c['stage'] == 'decompile'
                         and c.get('kind') in ('incomplete', 'diagnostic')
                         and c['stages'].get('behavior', {}).get('status') in ('ok', 'fail')]
        if informational:
            matched = [c for c in informational if c['stages']['behavior']['status'] == 'ok']
            out += ['### Marked outputs executed for information', '',
                    '%d outputs marked incomplete or with diagnostics still compiled and were '
                    'executed: %d matched the compiled program, %d did not. They count as '
                    'FAIL either way.' % (len(informational), len(matched),
                                          len(informational) - len(matched)), '']
            if matched:
                out += ['Matched despite the marker (the marker may be overly conservative '
                        'for these):', '']
                out += ['- ' + line for line in compact(matched)]
                out.append('')

        passes = [c for c in sc if c['outcome'] == 'PASS']
        out += ['### PASS (%d)' % len(passes), '']
        out += ['- ' + line for line in compact(passes)] or ['- none']
        out.append('')
    sys.stdout.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
